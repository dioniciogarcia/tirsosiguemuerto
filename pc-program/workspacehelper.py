# Where the program lives. For a packaged one-file .exe, __file__ points at a
# temporary unpack folder, NOT the folder the user put the .exe in - so we use
# the .exe's own folder, which is where config.json sits next to it.
if getattr(sys, "frozen", False):
    HERE = os.path.dirname(sys.executable)
else:
    HERE = os.path.dirname(os.path.abspath(__file__))
CONFIG_PATH = os.path.join(HERE, "config.json")
LOG_PATH = os.path.join(HERE, "workspacehelper.log")


def msgbox(text, title="WorkspaceHelper"):
    """Show a Windows pop-up so errors aren't silent. Falls back to the log."""
    try:
        import ctypes
        ctypes.windll.user32.MessageBoxW(0, text, title, 0x10)  # 0x10 = error icon
    except Exception:
        log("%s: %s" % (title, text))


# ----------------------------------------------------------------------------
# Small helpers
# ----------------------------------------------------------------------------
def log(message):
    """Write a timestamped line to the log file (and the console if visible)."""
    line = "%s  %s" % (dt.datetime.now().strftime("%Y-%m-%d %H:%M:%S"), message)
    try:
        print(line)
    except Exception:
        pass
    try:
        with open(LOG_PATH, "a", encoding="utf-8") as f:
            f.write(line + "\n")
    except Exception:
        pass


def load_config():
    if not os.path.exists(CONFIG_PATH):
        log("ERROR: config.json not found. Copy config.example.json to "
            "config.json and fill in your details.")
        return None
    try:
        with open(CONFIG_PATH, "r", encoding="utf-8") as f:
            cfg = json.load(f)
    except Exception as e:
        log("ERROR: config.json is not valid: %s" % e)
        return None

    # sensible defaults
    cfg.setdefault("desktime_process_name", "DeskTime.exe")
    cfg.setdefault("device_name", "Work PC")
    cfg.setdefault("timer_default_direction", "open_then_close")
    cfg.setdefault("poll_seconds", 1.5)
    cfg.setdefault("heartbeat_seconds", 5)
    cfg.setdefault("hours_refresh_seconds", 60)
    cfg.setdefault("screenshot_max_width", 900)
    cfg.setdefault("screenshot_quality", 50)
    return cfg


# ----------------------------------------------------------------------------
# Firebase Realtime Database (REST)
# ----------------------------------------------------------------------------
class Firebase:
    def __init__(self, base_url, secret):
        self.base = base_url.rstrip("/")
        self.secret = secret

    def _url(self, path):
        url = "%s/%s.json" % (self.base, path.strip("/"))
        if self.secret:
            url += "?auth=%s" % self.secret
        return url

    def get(self, path):
        r = requests.get(self._url(path), timeout=15)
        r.raise_for_status()
        return r.json()

    def put(self, path, data):
        r = requests.put(self._url(path), data=json.dumps(data), timeout=15)
        r.raise_for_status()
        return r.json()

    def patch(self, path, data):
        r = requests.patch(self._url(path), data=json.dumps(data), timeout=15)
        r.raise_for_status()
        return r.json()

    def delete(self, path):
        r = requests.delete(self._url(path), timeout=15)
        r.raise_for_status()


# ----------------------------------------------------------------------------
# DeskTime official API
# ----------------------------------------------------------------------------
def fetch_desktime(api_key, date=None):
    """Return a day's DeskTime summary, projects, and apps, or None.

    The /employee endpoint already includes projects and apps, and it
    authenticates with the apiKey as a query parameter. Pass date ("Y-m-d")
    for a past day; omit for today.
    """
    base = "https://desktime.com/api/v2/json"
    params = {"apiKey": api_key}
    if date:
        params["date"] = date
    try:
        r = requests.get("%s/employee" % base,
                         params=params,
                         headers={"Accept": "application/json"},
                         timeout=20)
        data = r.json()
    except Exception as e:
        log("DeskTime fetch failed: %s" % e)
        return None

    if not isinstance(data, dict) or "desktimeTime" not in data:
        log("DeskTime returned unexpected data: %s" % str(data)[:200])
        return None

    # Plain summary fields (safe for Firebase).
    out = {}
    for key in ("desktimeTime", "productiveTime", "productivity", "efficiency",
                "arrived", "left", "isOnline", "late", "atWorkTime"):
        if key in data:
            out[key] = data[key]

    if isinstance(data.get("activeProject"), dict):
        out["activeProject"] = data["activeProject"]

    # Projects is already a clean list.
    if isinstance(data.get("projects"), list):
        out["projects"] = data["projects"]

    # Apps come grouped by productivity, keyed by app name. App names contain
    # dots ("app.next.nuorder.com") which Firebase forbids as keys, so flatten
    # them into a plain list sorted by time used.
    apps_out = []
    cat_map = {"1": "productive", "0": "neutral", "-1": "unproductive"}
    raw_apps = data.get("apps", {})
    if isinstance(raw_apps, dict):
        for cat, group in raw_apps.items():
            if isinstance(group, dict):
                for info in group.values():
                    if isinstance(info, dict):
                        apps_out.append({
                            "name": info.get("name"),
                            "duration": info.get("duration", 0),
                            "type": info.get("type"),
                            "productivity": cat_map.get(str(cat), "neutral"),
                        })
    apps_out.sort(key=lambda a: a.get("duration") or 0, reverse=True)
    out["apps"] = apps_out

    return out or None


