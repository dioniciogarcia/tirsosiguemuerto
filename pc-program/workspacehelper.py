# The worker: does the real actions on this PC
# ----------------------------------------------------------------------------
def slugify(text):
    out = "".join(c.lower() if c.isalnum() else "-" for c in (text or "device"))
    out = "-".join(part for part in out.split("-") if part)
    return out or "device"


class Helper:
    def __init__(self, cfg):
        self.cfg = cfg
        self.fb = Firebase(cfg["firebase_url"], cfg.get("firebase_secret", ""))
        self.running = True
        self.mouse_running = False
        self.mouse_timer = None        # threading.Timer to auto-press F9
        self.shutdown_at = None        # "HH:MM" string, or None
        self._last_hours = 0
        # Each PC lives under devices/<id>/ so several people can share one
        # database. The id defaults to a slug of the device name.
        self.device_id = cfg.get("device_id") or slugify(cfg.get("device_name"))
        self.base = "devices/%s" % self.device_id
        # Scheduled routines: track what already fired this minute.
        self._fired_minute = ""
        self._fired = set()

    # ---- actions ----------------------------------------------------------
    def desktime_is_running(self):
        if not psutil:
            return None
        name = self.cfg["desktime_process_name"].lower()
        for p in psutil.process_iter(["name"]):
            try:
                if (p.info["name"] or "").lower() == name:
                    return True
            except Exception:
                pass
        return False

    def desktime_start(self):
        path = self.cfg.get("desktime_exe_path", "")
        if not path or not os.path.exists(path):
            log("Cannot open DeskTime: desktime_exe_path is missing/wrong.")
            return
        try:
            subprocess.Popen([path])
            log("DeskTime opened.")
        except Exception as e:
            log("Failed to open DeskTime: %s" % e)

    def desktime_stop(self):
        if not psutil:
            log("Cannot stop DeskTime: psutil not installed.")
            return
        name = self.cfg["desktime_process_name"].lower()
        killed = 0
        for p in psutil.process_iter(["name"]):
            try:
                if (p.info["name"] or "").lower() == name:
                    p.terminate()
                    killed += 1
            except Exception:
                pass
        log("DeskTime stopped (%d process(es))." % killed)

    def press_f9(self):
        if not pyautogui:
            log("Cannot press F9: pyautogui not installed.")
            return
        try:
            pyautogui.press("f9")
            log("Pressed F9.")
        except Exception as e:
            log("Failed to press F9: %s" % e)

    def mouse_start(self, minutes=0):
        self._cancel_mouse_timer()
        self.press_f9()
        self.mouse_running = True
        minutes = int(minutes or 0)
        if minutes > 0:
            self.mouse_timer = threading.Timer(minutes * 60, self.mouse_stop)
            self.mouse_timer.daemon = True
            self.mouse_timer.start()
            log("Mouse helper started for %d min." % minutes)
        else:
            log("Mouse helper started (no timer).")

    def mouse_stop(self):
        self._cancel_mouse_timer()
        if self.mouse_running:
            self.press_f9()
        self.mouse_running = False
        log("Mouse helper stopped.")

    def _cancel_mouse_timer(self):
        if self.mouse_timer:
            try:
                self.mouse_timer.cancel()
            except Exception:
                pass
            self.mouse_timer = None

    def desktime_timer(self, minutes, direction=None):
        """Open-now-close-later, or close-now-reopen-later."""
        direction = direction or self.cfg["timer_default_direction"]
        minutes = int(minutes or 0)
        if direction == "close_then_reopen":
            self.desktime_stop()
            if minutes > 0:
                t = threading.Timer(minutes * 60, self.desktime_start)
                t.daemon = True
                t.start()
        else:  # open_then_close
            self.desktime_start()
            if minutes > 0:
                t = threading.Timer(minutes * 60, self.desktime_stop)
                t.daemon = True
                t.start()
        log("DeskTime timer set: %s, %d min." % (direction, minutes))

    def take_screenshot(self):
        if not (pyautogui and Image):
            log("Cannot screenshot: pyautogui/Pillow missing.")
            return
        try:
            img = pyautogui.screenshot()
            max_w = int(self.cfg["screenshot_max_width"])
            if img.width > max_w:
                ratio = max_w / float(img.width)
                img = img.resize((max_w, int(img.height * ratio)))
            buf = io.BytesIO()
            img.convert("RGB").save(buf, format="JPEG",
                                    quality=int(self.cfg["screenshot_quality"]))
            b64 = base64.b64encode(buf.getvalue()).decode("ascii")
            self.fb.put(self.base + "/status/screenshot", {
                "jpg_b64": b64,
                "ts": int(time.time()),
            })
            log("Screenshot captured and sent (%d KB)." % (len(b64) // 1024))
        except Exception as e:
            log("Screenshot failed: %s" % e)

    def schedule_shutdown(self, hhmm):
        self.shutdown_at = hhmm
        log("Shutdown scheduled for %s." % hhmm)

    def cancel_shutdown(self):
        self.shutdown_at = None
        try:
            os.system("shutdown /a")
        except Exception:
            pass
        log("Shutdown cancelled.")

    def panic(self):
        log("PANIC: stopping DeskTime and mouse helper.")
        self.mouse_stop()
        self.desktime_stop()

    # ---- scheduled routines ----------------------------------------------
    def check_routines(self):
        """Run any routine whose time matches now (checked each loop)."""
        now = dt.datetime.now().strftime("%H:%M")
        if now != self._fired_minute:
            self._fired_minute = now
            self._fired = set()
        try:
            routines = self.fb.get(self.base + "/routines")
        except Exception:
            return
        if not isinstance(routines, dict):
            return
        for key, r in routines.items():
            if not isinstance(r, dict):
                continue
            if not r.get("enabled", True):
                continue
            if r.get("time") != now:
                continue
            days = r.get("days")
            if isinstance(days, list) and days:
                # days use Monday=0 .. Sunday=6, same as datetime.weekday()
                if dt.datetime.now().weekday() not in days:
                    continue
            if key in self._fired:
                continue
            self._fired.add(key)
            self._run_routine(r)

    def _run_routine(self, r):
        rtype = r.get("type", "")
        log("Routine firing: %s at %s" % (rtype, r.get("time")))
        if rtype == "desktime_open":
            self.desktime_start()
        elif rtype == "desktime_close":
            self.desktime_stop()
        elif rtype == "mouse_start":
            self.mouse_start(r.get("minutes", 0))
        elif rtype == "shutdown":
            os.system("shutdown /s /t 60")

    # ---- command dispatch -------------------------------------------------
    def handle_command(self, cmd):
        ctype = (cmd or {}).get("type", "")
        args = (cmd or {}).get("args", {}) or {}
        log("Command received: %s %s" % (ctype, args))
        if ctype == "desktime_start":
            self.desktime_start()
        elif ctype == "desktime_stop":
            self.desktime_stop()
        elif ctype == "desktime_timer":
            self.desktime_timer(args.get("minutes", 0), args.get("direction"))
        elif ctype == "mouse_start":
            self.mouse_start(args.get("minutes", 0))
        elif ctype == "mouse_stop":
            self.mouse_stop()
        elif ctype == "screenshot":
            self.take_screenshot()
        elif ctype == "shutdown_at":
            self.schedule_shutdown(args.get("time", ""))
        elif ctype == "shutdown_cancel":
            self.cancel_shutdown()
        elif ctype == "panic":
            self.panic()
        elif ctype == "fetch_history":
            self.fetch_history(args.get("date"))
        else:
            log("Unknown command type: %s" % ctype)

    def fetch_history(self, date):
        """Fetch a past day's DeskTime data and store it under history/<date>."""
        if not date:
            return
        data = fetch_desktime(self.cfg["desktime_api_key"], date)
        if data is not None:
            try:
                self.fb.put(self.base + "/history/" + date, data)
                log("Stored DeskTime history for %s" % date)
            except Exception as e:
                log("Failed to store history: %s" % e)

    # ---- background loops -------------------------------------------------
    def poll_commands_loop(self):
        delay = float(self.cfg["poll_seconds"])
        while self.running:
            try:
                cmds = self.fb.get(self.base + "/commands")
                if isinstance(cmds, dict):
                    # process oldest first, then delete each
                    for key in sorted(cmds.keys(),
                                      key=lambda k: cmds[k].get("ts", 0)
                                      if isinstance(cmds[k], dict) else 0):
                        self.handle_command(cmds[key])
                        try:
                            self.fb.put(self.base + "/last_ack", {
                                "key": key,
                                "type": cmds[key].get("type", "")
                                        if isinstance(cmds[key], dict) else "",
                                "ts": int(time.time()),
                            })
                        except Exception:
                            pass
                        try:
                            self.fb.delete(self.base + "/commands/%s" % key)
                        except Exception:
                            pass
            except Exception as e:
                log("Command poll error: %s" % e)
            time.sleep(delay)

    def status_loop(self):
        hb = float(self.cfg["heartbeat_seconds"])
        hours_every = float(self.cfg["hours_refresh_seconds"])
        last_hours = 0
        while self.running:
            try:
                status = {
                    "online": True,
                    "ts": int(time.time()),
                    "device_id": self.device_id,
                    "device_name": self.cfg["device_name"],
                    "desktime_running": self.desktime_is_running(),
                    "mouse_running": self.mouse_running,
                    "shutdown_at": self.shutdown_at,
                }
                self.fb.patch(self.base + "/status", status)

                now = time.time()
                if now - last_hours >= hours_every:
                    data = fetch_desktime(self.cfg["desktime_api_key"])
                    if data is not None:
                        self.fb.put(self.base + "/status/hours", data)
                    last_hours = now

                # scheduled shutdown check
                if self.shutdown_at:
                    nowhm = dt.datetime.now().strftime("%H:%M")
                    if nowhm == self.shutdown_at:
                        log("Shutdown time reached - shutting down in 60s.")
                        os.system("shutdown /s /t 60")
                        self.shutdown_at = None

                # scheduled routines
                self.check_routines()
            except Exception as e:
                log("Status loop error: %s" % e)
            time.sleep(hb)

    def start(self):
        threading.Thread(target=self.poll_commands_loop, daemon=True).start()
        threading.Thread(target=self.status_loop, daemon=True).start()
        log("WorkspaceHelper is running. Device: %s" % self.cfg["device_name"])


# ----------------------------------------------------------------------------
# Tray icon (so it lives next to the clock, no window)
# ----------------------------------------------------------------------------
def make_tray_image():
    img = PILImage.new("RGB", (64, 64), (124, 108, 246))
    d = ImageDraw.Draw(img)
    d.rectangle([28, 14, 36, 34], fill=(255, 255, 255))
    d.ellipse([18, 22, 46, 50], outline=(255, 255, 255), width=5)
    d.rectangle([18, 22, 46, 32], fill=(124, 108, 246))
    return img


def run_with_tray(helper):
    def on_quit(icon, item):
        helper.running = False
        try:
            helper.fb.patch(helper.base + "/status",
                            {"online": False, "ts": int(time.time())})
        except Exception:
            pass
        icon.stop()

    menu = pystray.Menu(
        pystray.MenuItem("WorkspaceHelper (running)", None, enabled=False),
        pystray.MenuItem("Quit", on_quit),
    )
    icon = pystray.Icon("WorkspaceHelper", make_tray_image(),
                        "WorkspaceHelper", menu)
    icon.run()


def main():
    cfg = load_config()
    if not cfg:
        msgbox("Could not find or read config.json.\n\nMake sure config.json "
               "is in the SAME folder as WorkspaceHelper.exe:\n\n%s" % CONFIG_PATH)
        sys.exit(1)

    helper = Helper(cfg)
    helper.start()

    if pystray:
        run_with_tray(helper)
    else:
        log("Tray library not available - running in console. Close this "
            "window to stop.")
        while helper.running:
            time.sleep(1)


if __name__ == "__main__":
    try:
        main()
    except Exception:
        err = traceback.format_exc()
        log("Fatal error:\n" + err)
        msgbox("WorkspaceHelper hit an error and stopped:\n\n" + err)
